using UnityEngine;

public class Player : MonoBehaviour
{
    public static Player instance;
    public InputControls controls { get; private set; }

    private void Awake()
    {
        if (instance == null)
        {
            instance = this;
            DontDestroyOnLoad(gameObject);
        }
        else
        {
            Destroy(gameObject);
        }
    }
}
